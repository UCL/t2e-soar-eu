        """Cliff's delta for (b vs a): 2*P(b>a)-1, on a fixed-seed subsample."""
        a = a[np.isfinite(a)]
        b = b[np.isfinite(b)]
        if len(a) == 0 or len(b) == 0:
            return float("nan")
        if len(a) > s:
            a = _drng.choice(a, s, replace=False)
        if len(b) > s:
            b = _drng.choice(b, s, replace=False)
        na, nb = len(a), len(b)
        r = rankdata(np.concatenate([a, b]))
        u = r[na:].sum() - nb * (nb + 1) / 2.0
        return 2.0 * (u / (na * nb)) - 1.0

