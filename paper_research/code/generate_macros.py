class MacroWriter:
    """Collect LaTeX macro definitions and write them to a file."""

    def __init__(self):
        self.macros: dict[str, str] = {}
        self.sections: list[tuple[str, list[str]]] = []
        self._current_section: str = ""
        self._current_keys: list[str] = []

    def section(self, name: str):
        if self._current_section:
            self.sections.append((self._current_section, self._current_keys))
        self._current_section = name
        self._current_keys = []

    def add(self, name: str, value, fmt: str = ""):
        """Add a macro. fmt is a Python format spec, e.g. '.0f', '.1f', '.3f'."""
        if isinstance(value, (int, np.integer)):
            text = f"{value:,}"
        elif isinstance(value, (float, np.floating)):
            text = f"{value:{fmt}}" if fmt else f"{value}"
        else:
            text = str(value)
        self.macros[name] = text
        self._current_keys.append(name)

    def write(self, path: Path):
        # Flush last section
        if self._current_section:
            self.sections.append((self._current_section, self._current_keys))

        lines = [
            "% Auto-generated by generate_macros.py — do not edit by hand.",
            "% Re-run: cd paper_research/code && python generate_macros.py",
            "",
        ]
        for section_name, keys in self.sections:
            lines.append(f"% {'─' * 60}")
            lines.append(f"% {section_name}")
            lines.append(f"% {'─' * 60}")
            for k in keys:
                v = self.macros[k]
                lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
            lines.append("")

        path.write_text("\n".join(lines) + "\n")
        print(f"Wrote {len(self.macros)} macros to {path}")


def main():
    mw = MacroWriter()

    # ══════════════════════════════════════════════════════════════════
    # Load data
    # ══════════════════════════════════════════════════════════════════
    from shared_config import MORPH_COLS as MORPH_COLS_LIST

    all_cols = (
        list(AXIS_COLS.values())
        + list(SVC_COLS.values())
        + list(MORPH_COLS.values())
        + list(DEMO_COLS.values())
        + list(CENTRALITY_COLS.values())
        + MORPH_COLS_LIST  # 400m morphometric columns for eta-squared / PCA
    )
    print("Loading data …")
    df = load_all_cached(columns=all_cols)
    n_total = len(df)
    n_cities = df["bounds_fid"].nunique()
    print(f"  {n_total:,} streets across {n_cities} cities")

    classified, thresholds = classify_octants(df)
    n_classified = len(classified)
    pct_classified = 100 * n_classified / n_total
    pct_excluded = 100 - pct_classified

    # Load boundaries for city metadata
    import geopandas as gpd

    bounds = gpd.read_file(BOUNDARIES_PATH).to_crs(3035)
    n_countries = bounds["country"].nunique()
    label_map = bounds.set_index("bounds_fid")["label"].to_dict()

    def city_fids(names):
        """Resolve city names to bounds_fids, tolerating composite labels.

        Matches an exact label first, then a composite label such as
        "Rotterdam [The Hague]". Substring matching is deliberately avoided
        (e.g. "Madrid" must not match "Rivas-Vaciamadrid").
        """
        fids = []
        for name in names:
            matches = bounds[bounds["label"] == name]
            if len(matches) == 0:
                matches = bounds[bounds["label"].str.startswith(f"{name} [")]
            if len(matches) == 0:
                print(f"  WARNING: no boundary label match for city '{name}'")
            fids.extend(matches["bounds_fid"].tolist())
        return fids

    # ══════════════════════════════════════════════════════════════════
    # Global counts
    # ══════════════════════════════════════════════════════════════════
    hq_fids = load_hq_fids(threshold=0.10)
    n_ml_restricted = len(hq_fids)

    mw.section("Global counts")
    mw.add("nCities", n_cities)
    mw.add("nCountries", n_countries)
    mw.add("nTotalM", n_total / 1e6, ".1f")
    mw.add("nClassifiedM", n_classified / 1e6, ".1f")
    mw.add("pctClassified", pct_classified, ".1f")
    mw.add("pctExcluded", pct_excluded, ".1f")
    mw.add("nMLRestrictedCities", n_ml_restricted)

    # ══════════════════════════════════════════════════════════════════
    # Plate 1: Octant counts and shares
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 1 — Octant counts and shares")
    oct_counts = classified["octant"].value_counts()
    total_oct = oct_counts.sum()

    for o in OCTANT_ORDER:
        n = oct_counts.get(o, 0)
        pct = 100 * n / total_oct
        mw.add(f"oct{o}countM", n / 1e6, ".1f")
        mw.add(f"oct{o}pct", pct, ".1f")

    # Intense types combined
    intense_pct = sum(oct_counts.get(o, 0) for o in ["HHH", "HHL", "HLH", "HLL"]) / total_oct * 100
    mw.add("octIntensePct", intense_pct, ".1f")
    light_pct = sum(oct_counts.get(o, 0) for o in ["LHH", "LHL", "LLH", "LLL"]) / total_oct * 100
    mw.add("pctLightTypes", light_pct, ".0f")
    intense_attached_pct = sum(oct_counts.get(o, 0) for o in ["HHH", "HHL"]) / total_oct * 100
    mw.add("pctIntenseAttached", intense_attached_pct, ".0f")

    # ══════════════════════════════════════════════════════════════════
    # Plate 1: Octant median axis values (Table 1)
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 1 — Octant median metric values (Table 1)")
    fsi_col = AXIS_COLS["intensity"]
    cont_col = AXIS_COLS["continuity"]  # frontage_max
    mad_col = AXIS_COLS["irregularity"]
    retail_col = SVC_COLS["retail"]

    for o in OCTANT_ORDER:
        mask = classified["octant"] == o
        sub = classified[mask]
        mw.add(f"oct{o}fsi", sub[fsi_col].median(), ".2f")
        mw.add(f"oct{o}cont", sub[cont_col].median(), ".3f")
        mw.add(f"oct{o}mad", sub[mad_col].median(), ".2f")
        mw.add(f"oct{o}retail", sub[retail_col].median(), ".0f")

    # ══════════════════════════════════════════════════════════════════
    # Plate 1: Axis independence statistics
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 1 — Axis correlations and independence")
    axes_data = classified[[fsi_col, cont_col, mad_col]].dropna()
    n_axes = len(axes_data)
    mw.add("nAxesM", n_axes / 1e6, ".1f")

    # Pearson correlations
    corr_ic = np.corrcoef(axes_data[fsi_col], axes_data[cont_col])[0, 1]
    corr_ii = np.corrcoef(axes_data[fsi_col], axes_data[mad_col])[0, 1]
    corr_ci = np.corrcoef(axes_data[cont_col], axes_data[mad_col])[0, 1]
    mw.add("rIntCont", corr_ic, ".2f")
    mw.add("rIntIrreg", corr_ii, ".2f")
    mw.add("rContIrreg", corr_ci, ".2f")

    # City-level Continuity vs Intensity correlation (frontage vs FSI, city medians)
    _city_med = classified.groupby("bounds_fid")[[cont_col, fsi_col]].median().dropna()
    mw.add("rFrontageFSIcity", pearsonr(_city_med[cont_col], _city_med[fsi_col])[0], ".2f")

    # VIF
    from sklearn.preprocessing import StandardScaler

    X_ax = StandardScaler().fit_transform(axes_data.values)
    R = np.corrcoef(X_ax, rowvar=False)
    R_inv = np.linalg.inv(R)
    max_vif = max(R_inv[i, i] for i in range(3))
    mw.add("maxVIF", max_vif, ".1f")

    # Observed/expected balance
    p_i = (axes_data[fsi_col] >= 1.0).mean()
    p_c = (axes_data[cont_col] >= 0.75).mean()
    p_r = (axes_data[mad_col] >= 4.0).mean()
    ratios = []
    for o in OCTANT_ORDER:
        obs = oct_counts.get(o, 0)
        p = 1.0
        p *= p_i if o[0] == "H" else (1 - p_i)
        p *= p_c if o[1] == "H" else (1 - p_c)
        p *= p_r if o[2] == "H" else (1 - p_r)
        exp = p * n_axes
        if exp > 0:
            ratios.append(obs / exp)
    mw.add("obsExpMin", min(ratios), ".2f")
    mw.add("obsExpMax", max(ratios), ".2f")

    # Cramer's V
    obs_arr = np.array([oct_counts.get(o, 0) for o in OCTANT_ORDER], dtype=float)
    exp_arr = np.array(
        [
            n_axes
            * (p_i if o[0] == "H" else 1 - p_i)
            * (p_c if o[1] == "H" else 1 - p_c)
            * (p_r if o[2] == "H" else 1 - p_r)
            for o in OCTANT_ORDER
        ]
    )
    chi2 = np.sum((obs_arr - exp_arr) ** 2 / exp_arr)
    cramers_v = np.sqrt(chi2 / (n_axes * 1))  # min(2,2,2)-1 = 1
    mw.add("cramersV", cramers_v, ".2f")

    # ══════════════════════════════════════════════════════════════════
    # Plate 1: Discrimination (eta-squared on non-axis variables)
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 1 — Discrimination (eta-squared)")
    morph_available = [c for c in MORPH_COLS_LIST if c in classified.columns]

    eta2_map = {}
    for col in morph_available:
        valid = classified[[col, "octant"]].dropna(subset=[col])
        vals = valid[col].values
        grand_mean = vals.mean()
        ss_total = np.sum((vals - grand_mean) ** 2)
        ss_between = 0.0
        for o in OCTANT_ORDER:
            g = valid.loc[valid["octant"] == o, col].values
            if len(g) > 0:
                ss_between += len(g) * (np.mean(g) - grand_mean) ** 2
        eta2_map[col] = ss_between / ss_total if ss_total > 0 else 0

    # Key eta-squared values cited in text
    eta2_vars = {
        "gsi": "cc_block_covered_ratio_median_400_wt",
        "height": "cc_mean_height_median_400_wt",
        "meanFloors": "cc_block_l_median_400_wt",
        "bldgDensity": "cc_building_400_nw",
    }
    for name, col in eta2_vars.items():
        if col in eta2_map:
            mw.add(f"etaSq{name[0].upper()}{name[1:]}", eta2_map[col], ".2f")

    # Intensity candidate discrimination (FSI vs height vs height_var vs GSI)
    intensity_candidates = {
        "fsi": "cc_block_far_median_400_wt",
        "height": "cc_mean_height_median_400_wt",
        "heightVar": "cc_mean_height_mad_400_wt",
        "gsiCand": "cc_block_covered_ratio_median_400_wt",
    }
    for name, col in intensity_candidates.items():
        if col in eta2_map:
            mw.add(f"etaSqCand{name[0].upper()}{name[1:]}", eta2_map[col], ".2f")

    # Mutual correlation among intensity candidates
    cand_cols = [
        "cc_block_far_median_400_wt",
        "cc_mean_height_median_400_wt",
        "cc_mean_height_mad_400_wt",
        "cc_block_covered_ratio_median_400_wt",
    ]
    cand_available = [c for c in cand_cols if c in classified.columns]
    if len(cand_available) >= 2:
        cand_corr = classified[cand_available].corr().values
        max_r_intensity = 0
        for i in range(len(cand_available)):
            for j in range(i + 1, len(cand_available)):
                max_r_intensity = max(max_r_intensity, abs(cand_corr[i, j]))
        mw.add("maxRIntensityCandidates", max_r_intensity, ".2f")

    # PCA top 3 (on complete cases only)
    from sklearn.decomposition import PCA

    morph_complete = classified[morph_available].dropna()
    X = StandardScaler().fit_transform(morph_complete.values)
    pca = PCA()
    pca.fit(X)
    pca3 = sum(pca.explained_variance_ratio_[:3]) * 100
    mw.add("pcaTopThree", pca3, ".0f")

    n_morph_vars = len(morph_available)
    mw.add("nMorphVars", n_morph_vars)

    # ══════════════════════════════════════════════════════════════════
    # Plate 1: Missing data rates
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 1 — Missing data rates")
    # Missing = NaN or zero (streets with no buildings in range have NaN/0)
    fsi_400_col = AXIS_COLS["intensity"]
    fsi_400_missing = (df[fsi_400_col].isna() | (df[fsi_400_col] == 0)).mean() * 100
    mw.add("pctMissingFSIfourHundred", fsi_400_missing, ".0f")
    # Pure NaN rate
    fsi_400_nan = df[fsi_400_col].isna().mean() * 100
    mw.add("pctNaNFSIfourHundred", fsi_400_nan, ".0f")

    # Also check 200m alternative if available
    fsi_200_col = "cc_block_far_median_200_wt"
    if fsi_200_col in df.columns:
        fsi_200_missing = (df[fsi_200_col].isna() | (df[fsi_200_col] == 0)).mean() * 100
        mw.add("pctMissingFSItwoHundred", fsi_200_missing, ".0f")
        fsi_200_nan = df[fsi_200_col].isna().mean() * 100
        mw.add("pctNaNFSItwoHundred", fsi_200_nan, ".0f")

    # ══════════════════════════════════════════════════════════════════
    # Plate 2/3: City-level axis values
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 2/3 — City-level axis values")
    city_meta = classified.merge(bounds[["bounds_fid", "label", "country"]], on="bounds_fid")
    city_axes = city_meta.groupby("bounds_fid").agg(
        {
            fsi_col: "median",
            cont_col: "median",
            mad_col: "median",
            "country": "first",
            "label": "first",
        }
    )

    def city_val(label, col, fmt=".2f"):
        row = city_axes[city_axes["label"] == label]
        if len(row) == 0:
            return np.nan
        return row[col].iloc[0]

    # Mediterranean FSI
    for city in ["Barcelona", "Athens", "Madrid"]:
        v = city_val(city, fsi_col)
        name = city.replace(" ", "")
        mw.add(f"fsi{name}", v, ".2f")

    # Nordic axis values
    nordic_cities = ["Oslo", "Bergen", "Helsinki", "Stockholm"]
    for city in nordic_cities:
        v_fsi = city_val(city, fsi_col)
        v_mad = city_val(city, mad_col)
        name = city.replace(" ", "")
        mw.add(f"fsi{name}", v_fsi, ".2f")
        mw.add(f"mad{name}", v_mad, ".1f")

    # Belgian city MAD values (organic medieval growth examples)
    belgian_mad_cities = ["Liège", "Brussels"]
    for city in belgian_mad_cities:
        v_mad = city_val(city, mad_col)
        # Strip diacritics for macro name
        name = city.replace(" ", "").replace("è", "e").replace("é", "e")
        mw.add(f"mad{name}", v_mad, ".1f")

    # NL/BE continuity and MAD
    nl_cities = city_axes[city_axes["country"] == "Netherlands"]
    be_cities = city_axes[city_axes["country"] == "Belgium"]
    mw.add("contNLmed", nl_cities[cont_col].median(), ".2f")
    mw.add("contBEmed", be_cities[cont_col].median(), ".2f")
    mw.add("madNLmin", nl_cities[mad_col].min(), ".1f")
    mw.add("madNLmax", nl_cities[mad_col].max(), ".1f")
    mw.add("madNLmed", nl_cities[mad_col].median(), ".1f")
    mw.add("madBEmin", be_cities[mad_col].min(), ".1f")
    mw.add("madBEmax", be_cities[mad_col].max(), ".1f")
    mw.add("madBEmed", be_cities[mad_col].median(), ".1f")

    # Country-level median FSI, continuity, MAD for Plate 2/3 text
    for country_name, code in [
        ("Spain", "ES"),
        ("Bulgaria", "BG"),
        ("Slovakia", "SK"),
        ("Portugal", "PT"),
        ("Austria", "AT"),
        ("Italy", "IT"),
        ("Greece", "EL"),
        ("Latvia", "LV"),
        ("Estonia", "EE"),
        ("France", "FR"),
        ("Ireland", "IE"),
        ("Germany", "DE"),
        ("Norway", "NO"),
        ("Switzerland", "CH"),
        ("Croatia", "HR"),
    ]:
        cc = city_axes[city_axes["country"] == country_name]
        if len(cc) == 0:
            continue
        mw.add(f"fsiCtry{code}", cc[fsi_col].median(), ".2f")
        mw.add(f"contCtry{code}", cc[cont_col].median(), ".2f")
        mw.add(f"madCtry{code}", cc[mad_col].median(), ".1f")

    # Within-city continuity percentages (pct streets >= frontage threshold)
    for city_name, macro_name in [
        ("Barcelona", "pctContBarcelona"),
        ("Athens", "pctContAthens"),
        ("Madrid", "pctContMadrid"),
        ("Amsterdam", "pctContAmsterdam"),
        ("Brussels", "pctContBrussels"),
    ]:
        mask = classified["bounds_fid"].isin(city_fids([city_name]))
        if mask.sum() == 0:
            continue
        pct = 100 * (classified.loc[mask, cont_col] >= 0.75).sum() / mask.sum()
        mw.add(macro_name, pct, ".0f")

    # NL continuity CV
    nl_cont_cv = nl_cities[cont_col].std() / nl_cities[cont_col].mean()
    mw.add("cvNLcont", nl_cont_cv, ".2f")

    # Poland: city-level median orientation MAD (cited at atlas.tex:94)
    pl_cities = city_axes[city_axes["country"] == "Poland"]
    if len(pl_cities) > 0:
        mw.add("madPolandAvg", pl_cities[mad_col].median(), ".1f")

    # Country-cluster service-distance medians (replace manual prose thresholds).
    # Clusters used in the Plate 9 continental-gradient discussion.
    CLUSTER_TREES_COOL = [
        "Norway",
        "Sweden",
        "Finland",
        "Denmark",
        "Estonia",
        "Latvia",
        "Lithuania",
        "Poland",
        "Germany",
    ]
    CLUSTER_TREES_WARM = ["Italy", "Spain", "Greece", "Portugal"]
    CLUSTER_EAT_SOUTH = ["Italy", "Spain", "Greece", "Portugal"]
    CLUSTER_EAT_NORTH = ["Norway", "Sweden", "Finland", "Denmark"]

    def _cluster_city_median(cluster, col):
        """Median across cities (city = bounds_fid) of city-level medians for col,
        restricted to the given country cluster."""
        meta = classified.merge(bounds[["bounds_fid", "country"]], on="bounds_fid")
        meta = meta[meta["country"].isin(cluster)]
        if len(meta) == 0:
            return float("nan")
        city_med = meta.groupby("bounds_fid")[col].median()
        return float(city_med.median())

    _trees_col = SVC_COLS["trees"]
    _eatdrink_col = SVC_COLS["eat_drink"]
    mw.add("distTreesCoolMed", _cluster_city_median(CLUSTER_TREES_COOL, _trees_col), ".0f")
    mw.add("distTreesWarmMed", _cluster_city_median(CLUSTER_TREES_WARM, _trees_col), ".0f")
    mw.add("distEatDrinkSouthMed", _cluster_city_median(CLUSTER_EAT_SOUTH, _eatdrink_col), ".0f")
    mw.add("distEatDrinkNorthMed", _cluster_city_median(CLUSTER_EAT_NORTH, _eatdrink_col), ".0f")

    # ══════════════════════════════════════════════════════════════════
    # Plate 4: Building morphometrics by octant
    # ══════════════════════════════════════════════════════════════════
    mw.section("Plate 4 — Building morphometrics by octant")
    height_col = MORPH_COLS["height"]
    # Per-octant morphometric macros
    morph_macro_map = {
        "height": ("height", ".1f"),
        "area": ("area", ".0f"),
        "perimeter": ("perim", ".0f"),
        "corners": ("corners", ".0f"),
        "compactness": ("compact", ".2f"),
        "volume": ("volume", ".0f"),
        "gsi": ("gsi", ".2f"),
        "osr": ("osr", ".2f"),
        "mean_floors": ("floors", ".1f"),
        "block_perim": ("blkPerim", ".0f"),
        "bldg_count": ("bldgCount", ".0f"),
        "block_count": ("blkCount", ".0f"),
    }
    for o in OCTANT_ORDER:
        mask = classified["octant"] == o
        sub = classified[mask]
        # FSI and continuity (full precision)
        if fsi_col in sub.columns:
            mw.add(f"oct{o}fsiFull", sub[fsi_col].median(), ".2f")
